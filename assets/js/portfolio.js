/* Indie Lane Photography - portfolio category pages
   (portfolio/<category>/index.html, generated by tools/build_portfolio.py) */
(function(){
  'use strict';

  // ---------- toast (used by the footer newsletter button) ----------
  var toast = document.getElementById('toast');
  var toastMsg = document.getElementById('toastMsg');
  var toastTimer;
  window.ilToast = function(msg){
    if(!toast) return;
    toastMsg.textContent = msg || '';
    toast.classList.add('show');
    clearTimeout(toastTimer);
    toastTimer = setTimeout(function(){ toast.classList.remove('show'); }, 2200);
  };

  // ---------- masonry ----------
  // Items keep Donna's curated order left to right: each one drops into the
  // currently shortest column, using the width/height baked into the markup.
  var grid = document.getElementById('pfGrid');
  var items = grid ? [].slice.call(grid.querySelectorAll('.pf-item')) : [];
  var colCount = 0;

  function columnsFor(width){ return width >= 1200 ? 3 : width >= 640 ? 2 : 1; }

  function layout(){
    var n = columnsFor(window.innerWidth);
    if(n === colCount) return;
    colCount = n;
    grid.classList.add('is-masonry');
    grid.innerHTML = '';
    var cols = [], heights = [];
    for(var i = 0; i < n; i++){
      var col = document.createElement('div');
      col.className = 'pf-col';
      grid.appendChild(col);
      cols.push(col);
      heights.push(0);
    }
    items.forEach(function(item){
      var k = heights.indexOf(Math.min.apply(null, heights));
      cols[k].appendChild(item);
      heights[k] += (+item.dataset.h / +item.dataset.w) || 1;
    });
  }

  if(grid && items.length){
    layout();
    var resizeTimer;
    window.addEventListener('resize', function(){
      clearTimeout(resizeTimer);
      resizeTimer = setTimeout(layout, 120);
    });
  }

  // ---------- full-screen viewer ----------
  var lb = document.getElementById('pfLightbox');
  var lbImg = document.getElementById('pfLbImg');
  var lbCount = document.getElementById('pfLbCount');
  var lbClose = document.getElementById('pfLbClose');
  var current = -1, lastFocus = null;

  function preload(i){
    var item = items[(i + items.length) % items.length];
    if(item){ var im = new Image(); im.src = item.getAttribute('href'); }
  }

  function show(i){
    current = (i + items.length) % items.length;
    var item = items[current];
    lbImg.src = item.getAttribute('href');
    lbImg.alt = item.querySelector('img').alt;
    lbCount.textContent = (current + 1) + ' / ' + items.length;
    preload(current + 1);
    preload(current - 1);
  }

  function open(i){
    lastFocus = document.activeElement;
    show(i);
    lb.classList.add('open');
    lb.setAttribute('aria-hidden', 'false');
    document.body.classList.add('gallery-open');
    lbClose.focus();
  }

  function close(){
    lb.classList.remove('open');
    lb.setAttribute('aria-hidden', 'true');
    document.body.classList.remove('gallery-open');
    current = -1;
    if(lastFocus) lastFocus.focus();
  }

  if(lb && items.length){
    items.forEach(function(item, i){
      item.addEventListener('click', function(e){ e.preventDefault(); open(i); });
    });
    lbClose.addEventListener('click', close);
    document.getElementById('pfLbPrev').addEventListener('click', function(){ show(current - 1); });
    document.getElementById('pfLbNext').addEventListener('click', function(){ show(current + 1); });
    lb.addEventListener('click', function(e){ if(e.target === lb) close(); });
    document.addEventListener('keydown', function(e){
      if(current < 0) return;
      if(e.key === 'Escape') close();
      else if(e.key === 'ArrowLeft') show(current - 1);
      else if(e.key === 'ArrowRight') show(current + 1);
    });
    var touchX = null;
    lb.addEventListener('touchstart', function(e){ touchX = e.touches[0].clientX; }, { passive: true });
    lb.addEventListener('touchend', function(e){
      if(touchX === null) return;
      var dx = e.changedTouches[0].clientX - touchX;
      if(Math.abs(dx) > 50) show(current + (dx < 0 ? 1 : -1));
      touchX = null;
    });
  }

  // ---------- mobile nav (glassy fullscreen) ----------
  var navToggle = document.getElementById('navToggle');
  var mobileNav = document.getElementById('mobileNav');
  var navClose = document.getElementById('navClose');
  if(navToggle && mobileNav){
    var openMenu = function(){
      mobileNav.classList.add('open');
      mobileNav.setAttribute('aria-hidden', 'false');
      navToggle.setAttribute('aria-expanded', 'true');
      document.body.classList.add('menu-open');
    };
    var closeMenu = function(){
      mobileNav.classList.remove('open');
      mobileNav.setAttribute('aria-hidden', 'true');
      navToggle.setAttribute('aria-expanded', 'false');
      document.body.classList.remove('menu-open');
    };
    navToggle.addEventListener('click', openMenu);
    if(navClose) navClose.addEventListener('click', closeMenu);
    mobileNav.querySelectorAll('a').forEach(function(a){ a.addEventListener('click', closeMenu); });
    document.addEventListener('keydown', function(e){
      if(e.key === 'Escape' && mobileNav.classList.contains('open')) closeMenu();
    });
  }

  // ---------- sticky bar ----------
  var bar = document.getElementById('stickyBar');
  if(bar){
    window.addEventListener('scroll', function(){
      bar.classList.toggle('visible', window.scrollY > window.innerHeight * 0.8);
    }, { passive: true });
  }

  // ---------- reveal on scroll ----------
  var io = new IntersectionObserver(function(entries){
    entries.forEach(function(en){
      if(en.isIntersecting){ en.target.classList.add('visible'); io.unobserve(en.target); }
    });
  }, { threshold: 0.1, rootMargin: '0px 0px -60px 0px' });
  document.querySelectorAll('.reveal, .line').forEach(function(el){ io.observe(el); });
})();
